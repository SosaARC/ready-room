const {JSDOM}=require('jsdom');const fs=require('fs');
const html=fs.readFileSync(process.argv[2],'utf8');
const errors=[];
const dom=new JSDOM(html,{runScripts:'dangerously',url:'https://example.org/',pretendToBeVisual:true,beforeParse(w){w.scrollTo=()=>{}}});
const w=dom.window;w.addEventListener('error',e=>errors.push(e.message));
const sleep=ms=>new Promise(r=>setTimeout(r,ms));const $=s=>w.document.querySelector(s);
const submit=sel=>$(sel).dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
const check=(n,c)=>{console.log((c?'PASS ':'FAIL ')+n);if(!c)process.exitCode=1};
(async()=>{await sleep(300);
 check('welcome links to quick start',!!$('a[href="#start"]'));
 w.location.hash='start';await sleep(60);
 check('quick start form shows',!!$('#startForm'));
 $('#s_name').value='Example Tutoring Co';$('#s_et').value='np501c3';$('#s_city').value='Greensboro';$('#s_county').value='Guilford';
 $('#s_ind').value='After-school tutoring';$('#s_rev').value='$90,000';$('#s_when').value='soon';
 [...w.document.querySelectorAll('input[name=focus]')].filter(x=>['youth-education','low-income'].includes(x.value)).forEach(x=>x.checked=true);
 w.document.querySelector('input[name=has][value=irs_501c3]').checked=true;
 submit('#startForm');await sleep(120);
 const t=$('#view').textContent;
 check('lands on shortlist',/Shortlist/.test(t));
 check('timeline note shown',/within 3 months/.test(t));
 check('business created',$('#bizSel').options.length===1&&/Example Tutoring Co/.test($('#bizSel').textContent));
 w.location.hash='profile';await sleep(60);
 check('budget filled for nonprofit',$('#p_budget')&&$('#p_budget').value==='$90,000');
 check('focus carried over',/youth/i.test($('#view').innerHTML)&&$('input[data-focus="youth-education"]')?.checked!==false);
 w.location.hash='vault';await sleep(60);
 check('501c3 letter placeholder in vault',/501\(c\)\(3\) determination letter/.test($('#view').textContent));
 console.log('ERRORS:',errors.length?errors:'none');if(errors.length)process.exitCode=1})();
